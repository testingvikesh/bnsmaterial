    /**
     * Map known English loanwords to Indic script.
     * Unknown or protected words stay English.
     *
     * @param  list<string>  $keep
     */
    public static function phrase(string $lang, string $text, array $keep = []): string
    {
        $text = trim($text);
        if ($text === '' || $lang === 'en') {
            return $text;
        }
        if (preg_match('/^https?:/i', $text) || preg_match('/^\+?\d[\d\s\-()]{6,}$/', $text)) {
            return $text;
        }
        $original = $text;

        $protected = [];
        $protect = function (string $value) use (&$protected): string {
            $key = "\x11P".count($protected)."\x11";
            $protected[$key] = $value;

            return $key;
        };

        $text = preg_replace_callback('/https?:\/\/[^\s]+/i', fn ($m) => $protect($m[0]), $text) ?? $text;
        $text = preg_replace_callback('/\b[A-Z0-9._%+\-]+@[A-Z0-9.\-]+\.[A-Z]{2,}\b/i', fn ($m) => $protect($m[0]), $text) ?? $text;
        $text = preg_replace_callback('/\b(?:B2B|B2C|OEM|ABB|RR|BNS|GST|ISO|SKU|ERP|CRM)\b/', fn ($m) => $protect($m[0]), $text) ?? $text;

        $pairs = self::pairs($lang);
        $keep = array_values(array_unique(array_filter(array_map('trim', $keep))));
        usort($keep, fn ($a, $b) => mb_strlen((string) $b) <=> mb_strlen((string) $a));
        foreach ($keep as $name) {
            $name = (string) $name;
            if ($name === '') {
                continue;
            }
            $lower = mb_strtolower($name);
            if (! str_contains($name, ' ') && isset($pairs[$lower])) {
                continue;
            }
            $text = preg_replace_callback(
                '/(?<![\p{L}\p{N}])'.preg_quote($name, '/').'(?![\p{L}\p{N}])/u',
                fn ($m) => $protect($m[0]),
                $text
            ) ?? $text;
        }

        uksort($pairs, fn ($a, $b) => mb_strlen($b) <=> mb_strlen($a));
        foreach ($pairs as $english => $local) {
            if ($local === '' || strcasecmp((string) $english, (string) $local) === 0) {
                continue;
            }
            $pattern = '/(?<![\p{L}\p{N}])'.preg_quote((string) $english, '/').'(?![\p{L}\p{N}])/iu';
            $text = preg_replace($pattern, $local, $text) ?? $text;
        }

        $out = strtr($text, $protected);
        if ($lang === 'mr') {
            $out = str_replace('अॅ', 'ॲ', $out);
        }
        if (self::shouldKeepEnglish($original, $out, $keep)) {
            return $original;
        }

        return $out;
    }

    /**
     * @param  list<string>  $lines
     * @param  list<string>  $keep
     * @return list<string>
     */
    public static function lines(string $lang, array $lines, array $keep = []): array
    {
        return array_values(array_map(fn ($line) => self::phrase($lang, (string) $line, $keep), $lines));
    }

    /**
     * Apply the same mapped-or-English rule to 16 Sanskar and 32 Gun copy trees.
     *
     * @param  list<string>  $keep
     */
    public static function apply(string $lang, mixed $value, array $keep = []): mixed
    {
        if (is_string($value)) {
            return self::phrase($lang, $value, $keep);
        }
        if (! is_array($value)) {
            return $value;
        }
        foreach ($value as $key => $item) {
            if (is_string($key) && in_array($key, ['status', 'url_slug', 'code'], true)) {
                continue;
            }
            $value[$key] = self::apply($lang, $item, $keep);
        }

        return $value;
    }

    public static function marathiPack(mixed $value): mixed
    {
        if (is_string($value)) {
            return str_replace('अॅ', 'ॲ', $value);
        }
        if (is_array($value)) {
            foreach ($value as $key => $item) {
                $value[$key] = self::marathiPack($item);
            }
        }

        return $value;
    }

    /**
     * @return list<string>
     */
    public static function keepNames(string ...$names): array
    {
        $keep = [];
        foreach ($names as $name) {
            $name = trim($name);
            if ($name === '' || str_contains(strtolower($name), 'required')) {
                continue;
            }
            $keep[] = $name;
            foreach (preg_split('/\s+/u', $name) ?: [] as $part) {
                $part = trim($part, " \t.,");
                if (strlen($part) >= 2) {
                    $keep[] = $part;
                }
            }
        }

        return array_values(array_unique($keep));
    }

    /**
     * Short labels stay fully English if any content word has no proper Indic form.
     *
     * @param  list<string>  $keep
     */
    private static function shouldKeepEnglish(string $original, string $converted, array $keep): bool
    {
        $words = preg_split('/\s+/u', trim($original)) ?: [];
        if (count($words) > 6) {
            return false;
        }
        preg_match_all('/[A-Za-z]{2,}/', $converted, $matches);
        $skip = [];
        foreach ($keep as $name) {
            $skip[strtolower(trim((string) $name))] = true;
        }
        foreach (['b2b', 'b2c', 'oem', 'abb', 'rr', 'bns', 'gst', 'iso', 'sku', 'erp', 'crm'] as $code) {
            $skip[$code] = true;
        }
        foreach ($matches[0] as $word) {
            if (! isset($skip[strtolower($word)])) {
                return true;
            }
        }

        return false;
    }

